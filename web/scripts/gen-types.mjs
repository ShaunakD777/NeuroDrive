// Generate src/api/generated.ts from the Python message models.
//
// 1. Ask Python (scripts/export_schemas.py) for the JSON Schema of every server message.
// 2. Convert each schema to a TypeScript type with json-schema-to-typescript.
// 3. Write them all to one file. The file is committed, so building the web app never needs Python.

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { compile } from "json-schema-to-typescript";

const repoRoot = fileURLToPath(new URL("../../", import.meta.url));
const outFile = fileURLToPath(new URL("../src/api/generated.ts", import.meta.url));

const json = execFileSync("uv", ["run", "python", "scripts/export_schemas.py"], {
  cwd: repoRoot,
  encoding: "utf8",
});
const schemas = JSON.parse(json);

const header = `// GENERATED by \`npm run gen:types\` from neurodrive/server/schemas.py. Do not edit by hand.\n\n`;
const parts = [];
for (const [name, schema] of Object.entries(schemas)) {
  parts.push(await compile(schema, name, { bannerComment: "", additionalProperties: false }));
}

writeFileSync(outFile, header + parts.join("\n"), "utf8");
console.log(`Wrote ${Object.keys(schemas).length} types to src/api/generated.ts`);
